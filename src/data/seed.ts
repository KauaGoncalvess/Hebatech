import type { GrauEstado, LinhaFicha, Produto } from "@/types/produto";

type EntradaNotebook = {
  codigo: string;
  slug: string;
  marca: string;
  modelo: string;
  preco: number;
  precoReferencia?: number;
  destaque?: boolean;
  cpuNome: string;
  cpuFamilia: string;
  cpuNucleos: number;
  cpuThreads: number;
  clockBase: string;
  clockTurbo: string;
  ramGb: number;
  ramTipo: string;
  ramSlots: string;
  ssdGb: number;
  ssdTipo: string;
  ssdLivre: string;
  telaPolegadas: number;
  telaResolucao: string;
  telaPainel: string;
  video: string;
  bateriaSaude: number;
  bateriaTipo: string;
  bateriaAutonomia: string;
  portas: string[];
  teclado: string;
  rede: string;
  sistema: string;
  pesoKg: number;
  grau: GrauEstado;
  resumo: string;
  observacoes: string[];
};

let sequencia = 0;

function notebook(e: EntradaNotebook): Produto {
  const ficha: LinhaFicha[] = [
    {
      rotulo: "Processador",
      valor: `${e.cpuNome} · ${e.cpuNucleos} núcleos / ${e.cpuThreads} threads`,
    },
    { rotulo: "Clock", valor: `${e.clockBase} base · ${e.clockTurbo} turbo` },
    { rotulo: "Memória", valor: `${e.ramGb} GB ${e.ramTipo}` },
    { rotulo: "Expansão de memória", valor: e.ramSlots },
    { rotulo: "Armazenamento", valor: `${e.ssdGb} GB ${e.ssdTipo}` },
    { rotulo: "Expansão de disco", valor: e.ssdLivre },
    {
      rotulo: "Tela",
      valor: `${e.telaPolegadas}" ${e.telaResolucao} ${e.telaPainel} · antirreflexo`,
    },
    { rotulo: "Vídeo", valor: e.video },
    {
      rotulo: "Bateria",
      valor: `${e.bateriaTipo} · ${e.bateriaSaude}% de saúde · ${e.bateriaAutonomia}`,
    },
    { rotulo: "Teclado", valor: e.teclado },
    { rotulo: "Rede", valor: e.rede },
    { rotulo: "Conexões", valor: e.portas.join(" · ") },
    { rotulo: "Sistema", valor: e.sistema },
    { rotulo: "Peso", valor: `${e.pesoKg.toFixed(2)} kg` },
  ];

  return {
    id: e.codigo,
    codigo: e.codigo,
    slug: e.slug,
    categoria: "notebook",
    marca: e.marca,
    modelo: e.modelo,
    condicao: "seminovo",
    preco: e.preco,
    precoReferencia: e.precoReferencia ?? null,
    // Carga de exemplo não tem compra real por trás, então não tem custo.
    custo: null,
    destaque: e.destaque ?? false,
    disponivel: true,
    resumo: e.resumo,
    cpuFamilia: e.cpuFamilia,
    cpuNome: e.cpuNome,
    ramGb: e.ramGb,
    armazenamentoGb: e.ssdGb,
    armazenamentoTipo: e.ssdTipo.split(" ")[1] ?? e.ssdTipo,
    telaPolegadas: e.telaPolegadas,
    telaResolucao: e.telaResolucao,
    bateriaSaude: e.bateriaSaude,
    pesoKg: e.pesoKg,
    ficha,
    estadoGrau: e.grau,
    estadoObservacoes: e.observacoes,
    garantiaDias: 90,
    fotos: [],
    ordem: sequencia++,
  };
}

type EntradaSimples = {
  codigo: string;
  slug: string;
  categoria: Produto["categoria"];
  marca: string;
  modelo: string;
  condicao?: Produto["condicao"];
  preco: number;
  precoReferencia?: number;
  destaque?: boolean;
  resumo: string;
  ficha: [string, string][];
  grau?: GrauEstado;
  observacoes?: string[];
  garantiaDias?: number;
  telaPolegadas?: number;
  telaResolucao?: string;
};

function produto(e: EntradaSimples): Produto {
  return {
    id: e.codigo,
    codigo: e.codigo,
    slug: e.slug,
    categoria: e.categoria,
    marca: e.marca,
    modelo: e.modelo,
    condicao: e.condicao ?? "seminovo",
    preco: e.preco,
    precoReferencia: e.precoReferencia ?? null,
    // Carga de exemplo não tem compra real por trás, então não tem custo.
    custo: null,
    destaque: e.destaque ?? false,
    disponivel: true,
    resumo: e.resumo,
    cpuFamilia: null,
    cpuNome: null,
    ramGb: null,
    armazenamentoGb: null,
    armazenamentoTipo: null,
    telaPolegadas: e.telaPolegadas ?? null,
    telaResolucao: e.telaResolucao ?? null,
    bateriaSaude: null,
    pesoKg: null,
    ficha: e.ficha.map(([rotulo, valor]) => ({ rotulo, valor })),
    estadoGrau: e.grau ?? null,
    estadoObservacoes: e.observacoes ?? [],
    garantiaDias: e.garantiaDias ?? 90,
    fotos: [],
    ordem: sequencia++,
  };
}

